import 'package:graphlink/src/model/gl_interface_definition.dart';
import 'package:graphlink/src/model/gl_type.dart';
import 'package:graphlink/src/model/member_field_conflict.dart';
import 'package:graphlink/src/model/new_parser/gl_parser.dart';
import 'package:graphlink/src/model/skipped_auto_query.dart';
import 'package:graphlink/src/parser_extensions/gl_expand_grammar_extension.dart';
import 'package:graphlink/src/parser_extensions/gl_grammar_extension.dart';
import 'package:graphlink/src/parser_extensions/gl_grammar_hoist_args_extension.dart';

final _conflictsCache = Expando<Map<String, MemberFieldConflict>>();
final _reachingCache = Expando<Map<String, MemberFieldConflict>>();

extension GLGrammarMemberConflictExtension on GLParser {
  /// GraphQL's "same response shape": nullability, list nesting and leaf type must match.
  String responseShape(GLType type) {
    final suffix = type.nullable ? '' : '!';
    if (type is GLListType) return '[${responseShape(type.type)}]$suffix';
    return '${typeRequiresProjection(type) ? 'object' : type.token}$suffix';
  }

  /// First clash per interface or union whose members give the same field a different shape.
  Map<String, MemberFieldConflict> get memberFieldConflicts =>
      _conflictsCache[this] ??= _computeMemberFieldConflicts();

  /// Every declared type from which an all-fields selection reaches an abstract type with a clash,
  /// mapped to the clash it reaches.
  Map<String, MemberFieldConflict> get typesReachingMemberConflicts =>
      _reachingCache[this] ??= _computeTypesReachingConflicts();

  void pruneQueriesReachingMemberConflicts() {
    final reaching = typesReachingMemberConflicts;
    if (reaching.isEmpty) return;
    for (final entry in queries.entries.toList()) {
      final def = entry.value;
      if (!def.isAutoGenerated) continue;
      for (final element in def.elements) {
        final conflict = reaching[element.returnType.inlineType.token];
        if (conflict == null) continue;
        removeAutoGeneratedQuery(entry.key, def);
        skippedAutoQueries.add(SkippedAutoQuery(name: def.token, type: def.type, conflict: conflict));
        break;
      }
    }
  }

  Map<String, MemberFieldConflict> _computeMemberFieldConflicts() {
    final result = <String, MemberFieldConflict>{};
    for (final abstract in interfaces.values) {
      final seen = <String, MapEntry<String, GLType>>{};
      for (final member in getTypesImplementing(abstract)) {
        for (final field in member.getSerializableFields(mode)) {
          final previous = seen[field.name.token];
          if (previous == null) {
            seen[field.name.token] = MapEntry(member.token, field.type);
            continue;
          }
          if (previous.key == member.token || responseShape(previous.value) == responseShape(field.type)) continue;
          result.putIfAbsent(
              abstract.token,
              () => MemberFieldConflict(
                    abstractType: abstract.token,
                    field: field.name.token,
                    firstMember: previous.key,
                    firstType: serializer.serializeType(previous.value),
                    secondMember: member.token,
                    secondType: serializer.serializeType(field.type),
                  ));
        }
      }
    }
    return result;
  }

  Map<String, MemberFieldConflict> _computeTypesReachingConflicts() {
    final conflicts = memberFieldConflicts;
    if (conflicts.isEmpty) return const {};
    final referencedBy = <String, Set<String>>{};
    void link(String from, String to) => referencedBy.putIfAbsent(to, () => {}).add(from);
    for (final type in [...types.values, ...interfaces.values]) {
      for (final field in type.getSerializableFields(mode)) {
        final target = field.type.firstType.token;
        if (types.containsKey(target) || interfaces.containsKey(target)) link(type.token, target);
      }
    }
    for (final iface in interfaces.values) {
      for (final member in getTypesImplementing(iface)) {
        link(iface.token, member.token);
      }
    }
    final reaching = {...conflicts};
    final pending = conflicts.keys.toList();
    while (pending.isNotEmpty) {
      final current = pending.removeLast();
      for (final parent in referencedBy[current] ?? const <String>{}) {
        if (reaching.containsKey(parent)) continue;
        reaching[parent] = reaching[current]!;
        pending.add(parent);
      }
    }
    return reaching;
  }
}
