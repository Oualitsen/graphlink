import 'package:graphlink/src/model/gl_queries.dart';
import 'package:graphlink/src/model/new_parser/gl_parser.dart';
import 'package:test/test.dart';

const _schema = '''
  type User { id: ID! name: String! }
  type Query { listUsers: [User!]! getUser(id: ID!): User! }

  query listUsers { listUsers { id } }
''';

GLParser _parse() => GLParser(autoGenerateQueries: true, generateAllFieldsFragments: true)..parse(_schema);

GLQueryDefinition _operation(GLParser g, String name) =>
    g.queries.values.firstWhere((q) => q.token == name);

void main() {
  test('a custom operation named like an auto-generated one is kept', () {
    final g = _parse();
    final listUsers = _operation(g, 'listUsers');
    expect(listUsers.isAutoGenerated, isFalse);
    expect(g.queries.values.where((q) => q.token == 'listUsers'), hasLength(1));
  });

  test('the other fields are still generated', () {
    expect(_operation(_parse(), 'getUser').isAutoGenerated, isTrue);
  });

  test('the skipped auto-generated operation is reported', () {
    final skipped = _parse().skippedAutoQueries.where((s) => s.name == 'listUsers');
    expect(skipped, hasLength(1));
    expect(skipped.single.shadowedByCustom, isTrue);
  });
}
